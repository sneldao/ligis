/**
 * Regenerate src/vk.ts from the compiled circuit (run after editing main.nr):
 *   pnpm --filter @ligis/circuits-zcash write:vk
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { CIRCUIT_DIR, resolveToolchain } from "../src/toolchain.js";

const tc = resolveToolchain();
if (typeof tc === "string") throw new Error(tc);
execFileSync(tc.nargo, ["compile"], { cwd: CIRCUIT_DIR, stdio: "inherit" });
const out = join(CIRCUIT_DIR, "target", "vk-out");
execFileSync(
  tc.bb,
  [
    "write_vk",
    "-b",
    join(CIRCUIT_DIR, "target", "ligis_credential_membership.json"),
    "-o",
    out,
  ],
  { stdio: "inherit" },
);
const vk = readFileSync(join(out, "vk")).toString("base64");
writeFileSync(
  join(CIRCUIT_DIR, "..", "src", "vk.ts"),
  `// Generated by scripts/write-vk.ts — UltraHonk verification key for\n// circuit/src/main.nr. Do not edit by hand.\nexport const MEMBERSHIP_VK_BASE64 =\n  "${vk}";\n`,
);
console.log(`wrote src/vk.ts (${Buffer.from(vk, "base64").length} bytes)`);
